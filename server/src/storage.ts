import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';

const endpoint = process.env.S3_ENDPOINT;
const accessKeyId = process.env.S3_ACCESS_KEY_ID;
const secretAccessKey = process.env.S3_SECRET_ACCESS_KEY;
const bucket = process.env.S3_BUCKET;
const publicUrl = process.env.MEDIA_PUBLIC_URL;

if (!endpoint || !accessKeyId || !secretAccessKey || !bucket || !publicUrl) {
  throw new Error('S3 configuration is incomplete in server/.env');
}

const client = new S3Client({
  endpoint,
  region: process.env.S3_REGION ?? 'us-east-1',
  // Required for local S3 servers: writes to localhost:8333/bucket/key
  forcePathStyle: process.env.S3_FORCE_PATH_STYLE === 'true',
  credentials: { accessKeyId, secretAccessKey },
  // Recent SDK versions add checksums that some S3-compatible servers reject.
  requestChecksumCalculation: 'WHEN_REQUIRED',
  responseChecksumValidation: 'WHEN_REQUIRED',
});

// Stores a file under the given key. The key is generated by the server, never taken from the user.
export async function uploadObject(key: string, body: Buffer, contentType: string): Promise<void> {
  await client.send(new PutObjectCommand({
    Bucket: bucket,
    Key: key,
    Body: body,
    ContentType: contentType,
  }));
}

export async function deleteObject(key: string): Promise<void> {
  await client.send(new DeleteObjectCommand({ Bucket: bucket, Key: key }));
}

export async function getObject(key: string) {
  return client.send(new GetObjectCommand({ Bucket: bucket, Key: key }));
}

// Only the key is stored in the database. The public address is built here.
export function getPublicUrl(key: string): string {
  return `${publicUrl}/${key}`;
}
